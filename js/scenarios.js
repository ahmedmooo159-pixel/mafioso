// Helper: احصل على سيناريو عشوائي من نوع معين (مع تجنب التكرار)
function getRandomScenario(accusationType, lastUsedId = null) {
  const pool = SCENARIOS[accusationType];
  if (!pool) return null;
  
  let available = pool.filter(s => s.id !== lastUsedId);
  if (available.length === 0) available = pool; // لو خلصنا، ابدأ من أول
  
  return available[Math.floor(Math.random() * available.length)];
}

// Helper: احصل على نوع تهمة عشوائي
function getRandomAccusationType() {
  const types = Object.keys(SCENARIOS);
  return types[Math.floor(Math.random() * types.length)];
}

// Helper: احصل على قصة كاملة مع أدوار مناسبة لعدد اللاعبين
function getScenarioForGame(playerCount, lastUsedId = null) {
  const accusation = getRandomAccusationType();
  const scenario = getRandomScenario(accusation, lastUsedId);
  
  // اختار شخصيات من القصة بعدد اللاعبين
  const shuffledRoles = [...scenario.roles].sort(() => Math.random() - 0.5);
  const selectedRoles = shuffledRoles.slice(0, playerCount);
  
  return {
    ...scenario,
    accusation,
    assignedRoles: selectedRoles
  };
}
