// Helper: احصل على دليل وخيط بداية النقاش
function getDiscussionStarter(accusationType, playerName) {
  const pool = DISCUSSION_STARTERS[accusationType] || DISCUSSION_STARTERS["قتل"];
  const template = pool[Math.floor(Math.random() * pool.length)];
  return template.replace(/{player}/g, playerName);
}

